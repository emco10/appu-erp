CREATE TABLE IF NOT EXISTS `tbl_remission_guide` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `number` varchar(30) NOT NULL,
  `status` varchar(30) NOT NULL DEFAULT 'Registrada',
  `guide_type` varchar(30) NOT NULL DEFAULT 'REMITENTE',
  `source_type` enum('invoice','receipt','sales_order') NOT NULL,
  `source_id` int(11) NOT NULL,
  `transfer_reason_code` varchar(30) NOT NULL DEFAULT 'VENTA',
  `transfer_reason` varchar(150) NOT NULL DEFAULT 'Venta',
  `transport_mode` varchar(30) NOT NULL DEFAULT 'PRIVADO',
  `issue_date` date NOT NULL,
  `transfer_date` date NOT NULL,
  `sender_ruc` varchar(11) NOT NULL DEFAULT '',
  `sender_name` varchar(200) NOT NULL DEFAULT '',
  `sender_address` varchar(300) NOT NULL DEFAULT '',
  `sender_ubigeo` varchar(6) NOT NULL DEFAULT '',
  `recipient_ruc` varchar(11) NOT NULL DEFAULT '',
  `recipient_name` varchar(200) NOT NULL DEFAULT '',
  `recipient_address` varchar(300) NOT NULL DEFAULT '',
  `recipient_ubigeo` varchar(6) NOT NULL DEFAULT '',
  `origin_address` varchar(300) NOT NULL DEFAULT '',
  `origin_ubigeo` varchar(6) NOT NULL DEFAULT '',
  `origin_establishment_code` varchar(10) NOT NULL DEFAULT '',
  `destination_address` varchar(300) NOT NULL DEFAULT '',
  `destination_ubigeo` varchar(6) NOT NULL DEFAULT '',
  `destination_establishment_code` varchar(10) NOT NULL DEFAULT '',
  `carrier_ruc` varchar(11) NOT NULL DEFAULT '',
  `carrier_name` varchar(200) NOT NULL DEFAULT '',
  `vehicle_plate` varchar(20) NOT NULL DEFAULT '',
  `vehicle_brand` varchar(100) NOT NULL DEFAULT '',
  `driver_doc_type` varchar(10) NOT NULL DEFAULT '',
  `driver_doc_number` varchar(20) NOT NULL DEFAULT '',
  `driver_name` varchar(200) NOT NULL DEFAULT '',
  `driver_license` varchar(30) NOT NULL DEFAULT '',
  `notes` varchar(500) NOT NULL DEFAULT '',
  `created_by` int(11) NOT NULL,
  `registration_date` datetime NOT NULL DEFAULT current_timestamp(),
  `last_update` datetime NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_remission_guide_number` (`number`),
  KEY `idx_remission_guide_status_date` (`status`,`transfer_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `tbl_remission_guide_detail` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `remission_guide_id` int(11) NOT NULL,
  `source_detail_id` int(11) NOT NULL,
  `product_id` int(11) NOT NULL,
  `item_code` varchar(100) NOT NULL DEFAULT '',
  `description` varchar(300) NOT NULL DEFAULT '',
  `unit_code` varchar(10) NOT NULL DEFAULT 'NIU',
  `quantity` decimal(12,3) NOT NULL,
  `gross_weight` decimal(12,3) NOT NULL DEFAULT 0,
  `weight_unit` varchar(10) NOT NULL DEFAULT 'KGM',
  `packages` int(11) NOT NULL DEFAULT 0,
  `lot_number` varchar(50) NOT NULL DEFAULT '',
  `serial_number` varchar(100) NOT NULL DEFAULT '',
  PRIMARY KEY (`id`),
  KEY `idx_remission_guide_detail_guide` (`remission_guide_id`),
  KEY `idx_remission_guide_detail_source` (`source_detail_id`),
  KEY `idx_remission_guide_detail_product` (`product_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
